-- Day 2: Create RAW tables (Ashraf)
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE ATMOSYNC_WH;
USE DATABASE ATMOSYNC_DB;
USE SCHEMA RAW;

-- 1) Raw table: Kafka connector loads the full JSON here
CREATE TABLE IF NOT EXISTS ATMOSYNC_DB.RAW.IOT_SENSOR_RAW (
  RECORD_CONTENT  VARIANT,
  RECORD_METADATA VARIANT
);

-- 2) Sensor table: one column for each JSON field, plus location
CREATE TABLE IF NOT EXISTS ATMOSYNC_DB.RAW.IOT_SENSOR_READINGS (
  CONTAINER_ID     VARCHAR,
  SENSOR_ID        VARCHAR,
  EVENT_TIMESTAMP  TIMESTAMP_TZ,
  TEMPERATURE      FLOAT,
  HUMIDITY         FLOAT,
  VIBRATION        FLOAT,
  LOCATION         VARCHAR,
  LOADED_AT        TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 3) Commodity prices (loaded on Day 5)
CREATE TABLE IF NOT EXISTS ATMOSYNC_DB.RAW.COMMODITY_PRICES_RAW (
  COMMODITY   VARCHAR,
  MARKET      VARCHAR,
  PRICE       FLOAT,
  PRICE_DATE  DATE,
  LOADED_AT   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 4) Add LOCATION if the table was created without it
ALTER TABLE ATMOSYNC_DB.RAW.IOT_SENSOR_READINGS
  ADD COLUMN IF NOT EXISTS LOCATION VARCHAR;

